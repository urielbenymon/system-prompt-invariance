"""
PURPOSE:
Interactively review WordNet-supported synonym substitutions for the
BiGGen system-prompt invariance experiment.

For each prompt, candidates are considered in original left-to-right rank order.
Candidates with no eligible WordNet synonyms are skipped automatically. For
each usable synonym, the script displays:

    - the original BiGGen system prompt
    - the original BiGGen scoring rubric
    - WordNet synset evidence
    - the proposed synonym substitution
    - the resulting transformed system prompt
    - a contextual-equivalence checklist

The researcher then decides whether the substitution is contextually equivalent,
grammatically well-formed, and preserves the original system instruction and
BiGGen rubric.

HOW TO USE:
Place this script in the same folder as:

    wordnet_lookup_results.jsonl
    biggen_system_prompt_vs_instruction.jsonl

Run:

    python .\05_review_wordnet_synonyms.py

For each proposed substitution, enter:

    a = approve this substitution and finish this prompt
    r = reject this substitution and continue
    f = flag this substitution for discussion and continue
    q = quit

Results are saved incrementally to:

    wordnet_contextual_review_results.jsonl
"""

import json
from pathlib import Path


# ---------------------------------------------------------------------
# FILE PATHS
# ---------------------------------------------------------------------

# WordNet evidence generated by 04_wordnet_synonym_lookup.py.
LOOKUP_FILE = Path(
    "wordnet_lookup_results.jsonl"
)

# Untouched original BiGGen system_prompt_vs_instruction dataset.
BASE_FILE = Path(
    "biggen_system_prompt_vs_instruction.jsonl"
)

# Human contextual-equivalence review results.
OUTPUT_FILE = Path(
    "wordnet_contextual_review_results.jsonl"
)


# ---------------------------------------------------------------------
# JSONL HELPERS
# ---------------------------------------------------------------------

def load_jsonl(path):
    """
    Load a JSONL file into a list of dictionaries.
    """

    rows = []

    with path.open(
        "r",
        encoding="utf-8"
    ) as file:

        for line_number, line in enumerate(
            file,
            start=1
        ):

            if not line.strip():
                continue

            try:

                rows.append(
                    json.loads(line)
                )

            except json.JSONDecodeError as error:

                raise ValueError(
                    f"Invalid JSON on line "
                    f"{line_number} of {path}: "
                    f"{error}"
                )

    return rows


def save_jsonl(
    path,
    rows
):
    """
    Save a list of dictionaries as JSONL.
    """

    with path.open(
        "w",
        encoding="utf-8"
    ) as file:

        for row in rows:

            file.write(
                json.dumps(
                    row,
                    ensure_ascii=False
                )
                + "\n"
            )


# ---------------------------------------------------------------------
# TEXT HELPERS
# ---------------------------------------------------------------------

def preserve_case(
    source_word,
    replacement_word
):
    """
    Preserve simple capitalization from the source word.

    Examples:
        Evaluate -> Assess
        evaluate -> assess
    """

    if source_word[:1].isupper():

        return (
            replacement_word[:1].upper()
            + replacement_word[1:]
        )

    return replacement_word


def replace_nth_occurrence(
    text,
    source_word,
    replacement_word,
    occurrence_number
):
    """
    Replace exactly the specified 1-indexed occurrence of source_word.

    Example:

        text = "news ... news ... news"
        occurrence_number = 2

    Only the second occurrence is replaced.
    """

    if occurrence_number < 1:

        raise ValueError(
            "occurrence_number must be "
            "at least 1."
        )

    start = 0

    for current_occurrence in range(
        1,
        occurrence_number + 1
    ):

        index = text.find(
            source_word,
            start
        )

        if index == -1:

            raise ValueError(
                f"Could not find occurrence "
                f"#{occurrence_number} of "
                f"{source_word!r}."
            )

        if (
            current_occurrence
            == occurrence_number
        ):

            return (
                text[:index]
                + replacement_word
                + text[
                    index
                    + len(source_word):
                ]
            )

        start = (
            index
            + len(source_word)
        )

    raise ValueError(
        "Unexpected occurrence "
        "replacement error."
    )


def make_substituted_prompt(
    original_prompt,
    source_word,
    replacement_word,
    occurrence_number
):
    """
    Replace exactly one specified occurrence of the target word.
    """

    replacement_word = preserve_case(
        source_word,
        replacement_word
    )

    return replace_nth_occurrence(
        original_prompt,
        source_word,
        replacement_word,
        occurrence_number
    )


# ---------------------------------------------------------------------
# DISPLAY HELPERS
# ---------------------------------------------------------------------

def print_header(
    prompt_index,
    row,
    score_rubric
):
    """
    Display prompt-level information, including the original
    BiGGen instance-specific scoring rubric.
    """

    print(
        "\n"
        + "=" * 110
    )

    print(
        f"PROMPT {prompt_index}"
    )

    print(
        "=" * 110
    )

    print(
        "\nBASE ID:"
    )

    print(
        row.get("base_id")
    )

    print(
        "\nORIGINAL SYSTEM PROMPT:"
    )

    print(
        row.get(
            "system_prompt_original"
        )
    )

    print(
        "\nSELECTION RULE:"
    )

    print(
        row.get(
            "selection_rule"
        )
    )

    print(
        "\nADDITIONAL CONSTRAINT:"
    )

    print(
        row.get(
            "additional_constraint"
        )
    )

    print(
        "\nBIGGEN SCORE RUBRIC:"
    )

    print(
        json.dumps(
            score_rubric,
            indent=2,
            ensure_ascii=False
        )
    )


def print_synset_evidence(
    candidate,
    synonym,
    matching_synsets
):
    """
    Display WordNet evidence supporting a proposed substitution.
    """

    print(
        "\nWORDNET EVIDENCE:"
    )

    print(
        f"Target word: "
        f"{candidate.get('word')} "
        f"[POS: "
        f"{candidate.get('pos')}]"
    )

    print(
        f"Proposed synonym: "
        f"{synonym}"
    )

    if not matching_synsets:

        print(
            "No matching synset evidence "
            "found for this synonym."
        )

        return

    for synset in matching_synsets:

        print(
            "\n  Synset:"
        )

        print(
            f"    "
            f"{synset.get('synset')}"
        )

        print(
            "  Definition:"
        )

        print(
            f"    "
            f"{synset.get('definition')}"
        )

        examples = synset.get(
            "examples",
            []
        )

        if examples:

            print(
                "  Examples:"
            )

            for example in examples:

                print(
                    f"    - {example}"
                )

        print(
            "  Eligible lemmas "
            "in this synset:"
        )

        print(
            "    "
            + ", ".join(
                synset.get(
                    "eligible_one_word_lemmas",
                    []
                )
            )
        )


# ---------------------------------------------------------------------
# CANDIDATE / SYNONYM HELPERS
# ---------------------------------------------------------------------

def get_matching_synsets(
    candidate,
    synonym
):
    """
    Return WordNet synsets in which the proposed synonym appears
    as an eligible one-word lemma.
    """

    matching = []

    for synset in candidate.get(
        "synsets",
        []
    ):

        eligible = synset.get(
            "eligible_one_word_lemmas",
            []
        )

        if synonym in eligible:

            matching.append(
                synset
            )

    return matching


def get_occurrence_number(
    candidate_lookups,
    current_candidate
):
    """
    Determine which left-to-right occurrence of the same source word
    the current candidate represents.

    Example:

        Candidate #3 = news
        Candidate #5 = news
        Candidate #8 = news

    Their occurrence numbers become 1, 2, and 3.
    """

    current_rank = (
        current_candidate.get(
            "candidate_rank"
        )
    )

    source_word = (
        current_candidate.get(
            "word"
        )
    )

    same_word_candidates_so_far = [
        candidate
        for candidate in candidate_lookups
        if (
            candidate.get(
                "candidate_rank",
                999999
            )
            <= current_rank
            and
            candidate.get(
                "word"
            )
            == source_word
        )
    ]

    return len(
        same_word_candidates_so_far
    )


# ---------------------------------------------------------------------
# MAIN WORKFLOW
# ---------------------------------------------------------------------

def main():

    # -------------------------------------------------------------
    # VERIFY REQUIRED FILES
    # -------------------------------------------------------------

    if not LOOKUP_FILE.exists():

        raise FileNotFoundError(
            f"Could not find "
            f"{LOOKUP_FILE}."
        )

    if not BASE_FILE.exists():

        raise FileNotFoundError(
            f"Could not find "
            f"{BASE_FILE}.\n\n"
            "Make sure the untouched "
            "BiGGen baseline JSONL is "
            "in the project folder."
        )

    # -------------------------------------------------------------
    # LOAD WORDNET LOOKUP DATA
    # -------------------------------------------------------------

    rows = load_jsonl(
        LOOKUP_FILE
    )

    print(
        f"Loaded {len(rows)} prompts "
        f"from {LOOKUP_FILE}."
    )

    # -------------------------------------------------------------
    # LOAD ORIGINAL BIGGEN DATA
    # -------------------------------------------------------------

    base_rows = load_jsonl(
        BASE_FILE
    )

    print(
        f"Loaded {len(base_rows)} "
        f"original BiGGen rows "
        f"from {BASE_FILE}."
    )

    # Create ID -> original row mapping.
    base_by_id = {
        row["id"]: row
        for row in base_rows
    }

    # Store completed prompt reviews.
    output_rows = []

    # -------------------------------------------------------------
    # PROCESS EACH PROMPT
    # -------------------------------------------------------------

    for prompt_index, row in enumerate(
        rows
    ):

        # Retrieve the BiGGen base identifier.
        base_id = row.get(
            "base_id"
        )

        # Verify that the original benchmark row exists.
        if base_id not in base_by_id:

            raise ValueError(
                f"Could not find original "
                f"BiGGen row for base_id "
                f"{base_id!r}."
            )

        # Retrieve original BiGGen data.
        base_row = base_by_id[
            base_id
        ]

        # Retrieve the instance-specific rubric.
        score_rubric = base_row.get(
            "score_rubric"
        )

        # Retrieve the original system prompt.
        original_prompt = row.get(
            "system_prompt_original"
        )

        # ---------------------------------------------------------
        # SANITY CHECK ORIGINAL PROMPT
        # ---------------------------------------------------------

        if (
            base_row.get(
                "system_prompt"
            )
            != original_prompt
        ):

            raise ValueError(
                f"Prompt mismatch for "
                f"{base_id}.\n"
                "The WordNet lookup file's "
                "original prompt does not "
                "match the untouched "
                "BiGGen baseline."
            )

        # ---------------------------------------------------------
        # DISPLAY PROMPT + RUBRIC
        # ---------------------------------------------------------

        print_header(
            prompt_index,
            row,
            score_rubric
        )

        # ---------------------------------------------------------
        # INITIALIZE PROMPT REVIEW RECORD
        # ---------------------------------------------------------

        prompt_result = {

            "base_id": base_id,

            "instance_idx": (
                row.get(
                    "instance_idx"
                )
            ),

            "system_prompt_original": (
                original_prompt
            ),

            # Preserve original rubric for auditability.
            "score_rubric": (
                score_rubric
            ),

            "candidate_reviews": [],

            "selected_candidate_rank": None,

            "selected_word": None,

            "selected_synonym": None,

            "selected_synset": None,

            "selected_occurrence_number": None,

            "system_prompt_transformed": None,

            "selection_status": (
                "no_approved_substitution_yet"
            ),
        }

        candidate_lookups = row.get(
            "candidate_lookups",
            []
        )

        # Preserve original candidate order.
        candidate_lookups = sorted(
            candidate_lookups,
            key=lambda candidate:
            candidate.get(
                "candidate_rank",
                999999
            )
        )

        prompt_finished = False

        # ---------------------------------------------------------
        # REVIEW CANDIDATES IN LEFT-TO-RIGHT ORDER
        # ---------------------------------------------------------

        for candidate in candidate_lookups:

            candidate_rank = (
                candidate.get(
                    "candidate_rank"
                )
            )

            source_word = (
                candidate.get(
                    "word"
                )
            )

            pos = candidate.get(
                "pos"
            )

            occurrence_number = (
                get_occurrence_number(
                    candidate_lookups,
                    candidate
                )
            )

            synonyms = candidate.get(
                "eligible_synonym_candidates",
                []
            )

            lookup_status = (
                candidate.get(
                    "lookup_status"
                )
            )

            # -----------------------------------------------------
            # AUTOMATICALLY SKIP EMPTY WORDNET CANDIDATES
            # -----------------------------------------------------

            if (
                lookup_status
                != "eligible_synonyms_found"
                or not synonyms
            ):

                prompt_result[
                    "candidate_reviews"
                ].append({

                    "candidate_rank": (
                        candidate_rank
                    ),

                    "word": (
                        source_word
                    ),

                    "pos": (
                        pos
                    ),

                    "occurrence_number": (
                        occurrence_number
                    ),

                    "status": (
                        "automatically_skipped_"
                        "no_eligible_synonyms"
                    ),

                    "synonym_reviews": [],
                })

                print(
                    f"\nCandidate "
                    f"#{candidate_rank}: "
                    f"{source_word} "
                    f"[{pos}] "
                    f"(occurrence "
                    f"#{occurrence_number})"
                )

                print(
                    "Skipped automatically: "
                    "no eligible WordNet synonym."
                )

                continue

            # -----------------------------------------------------
            # BEGIN MANUAL REVIEW FOR THIS TARGET WORD
            # -----------------------------------------------------

            print(
                "\n"
                + "-" * 110
            )

            print(
                f"CANDIDATE "
                f"#{candidate_rank}: "
                f"{source_word} "
                f"[{pos}] "
                f"(occurrence "
                f"#{occurrence_number})"
            )

            candidate_review = {

                "candidate_rank": (
                    candidate_rank
                ),

                "word": (
                    source_word
                ),

                "pos": (
                    pos
                ),

                "occurrence_number": (
                    occurrence_number
                ),

                "lookup_status": (
                    lookup_status
                ),

                "synonym_reviews": [],
            }

            # -----------------------------------------------------
            # REVIEW EACH WORDNET SYNONYM
            # -----------------------------------------------------

            for synonym in synonyms:

                transformed_prompt = (
                    make_substituted_prompt(
                        original_prompt,
                        source_word,
                        synonym,
                        occurrence_number
                    )
                )

                matching_synsets = (
                    get_matching_synsets(
                        candidate,
                        synonym
                    )
                )

                print(
                    "\n"
                    + "." * 110
                )

                print_synset_evidence(
                    candidate,
                    synonym,
                    matching_synsets
                )

                print(
                    "\nORIGINAL:"
                )

                print(
                    original_prompt
                )

                print(
                    "\nPROPOSED:"
                )

                print(
                    transformed_prompt
                )

                # -------------------------------------------------
                # REPRINT RUBRIC NEXT TO PROPOSED SUBSTITUTION
                # -------------------------------------------------

                print(
                    "\nBIGGEN SCORE RUBRIC:"
                )

                print(
                    json.dumps(
                        score_rubric,
                        indent=2,
                        ensure_ascii=False
                    )
                )

                # -------------------------------------------------
                # CONTEXTUAL-EQUIVALENCE CHECKLIST
                # -------------------------------------------------

                print(
                    "\nCONTEXTUAL-EQUIVALENCE CHECK:"
                )

                print(
                    "[ ] Grammatically well-formed "
                    "after direct substitution"
                )

                print(
                    "[ ] Same task operation"
                )

                print(
                    "[ ] Same arguments / referents"
                )

                print(
                    "[ ] Same scope"
                )

                print(
                    "[ ] Same polarity / "
                    "modality / force"
                )

                print(
                    "[ ] Same required content "
                    "and output constraints"
                )

                print(
                    "[ ] Original BiGGen "
                    "reference answer still applies"
                )

                print(
                    "[ ] Original BiGGen rubric "
                    "still applies verbatim"
                )

                # -------------------------------------------------
                # USER DECISION
                # -------------------------------------------------

                while True:

                    decision = input(
                        "\nDecision "
                        "[a = approve, "
                        "r = reject, "
                        "f = flag, "
                        "q = quit]: "
                    ).strip().lower()

                    if decision in {
                        "a",
                        "r",
                        "f",
                        "q"
                    }:

                        break

                    print(
                        "Please enter "
                        "a, r, f, or q."
                    )

                # -------------------------------------------------
                # QUIT + SAVE CURRENT PROGRESS
                # -------------------------------------------------

                if decision == "q":

                    print(
                        "\nReview stopped "
                        "by user."
                    )

                    prompt_result[
                        "candidate_reviews"
                    ].append(
                        candidate_review
                    )

                    current_output = (
                        output_rows
                        + [prompt_result]
                    )

                    save_jsonl(
                        OUTPUT_FILE,
                        current_output
                    )

                    print(
                        f"\nProgress saved to:\n"
                        f"{OUTPUT_FILE}"
                    )

                    return

                decision_map = {

                    "a": "approved",

                    "r": "rejected",

                    "f": (
                        "flagged_for_discussion"
                    ),
                }

                note = input(
                    "Optional note "
                    "(press Enter for none): "
                ).strip()

                synonym_review = {

                    "synonym": (
                        synonym
                    ),

                    "decision": (
                        decision_map[
                            decision
                        ]
                    ),

                    "matching_synsets": [
                        synset.get(
                            "synset"
                        )
                        for synset
                        in matching_synsets
                    ],

                    "transformed_prompt": (
                        transformed_prompt
                    ),

                    "notes": (
                        note
                    ),
                }

                candidate_review[
                    "synonym_reviews"
                ].append(
                    synonym_review
                )

                # -------------------------------------------------
                # INCREMENTAL SAVE AFTER EVERY DECISION
                # -------------------------------------------------

                temporary_prompt_result = dict(
                    prompt_result
                )

                temporary_candidate_reviews = list(
                    prompt_result[
                        "candidate_reviews"
                    ]
                )

                temporary_candidate_reviews.append(
                    candidate_review
                )

                temporary_prompt_result[
                    "candidate_reviews"
                ] = (
                    temporary_candidate_reviews
                )

                save_jsonl(
                    OUTPUT_FILE,
                    output_rows
                    + [
                        temporary_prompt_result
                    ]
                )

                # -------------------------------------------------
                # APPROVAL HANDLING
                # -------------------------------------------------

                if decision == "a":

                    prompt_result[
                        "selected_candidate_rank"
                    ] = (
                        candidate_rank
                    )

                    prompt_result[
                        "selected_word"
                    ] = (
                        source_word
                    )

                    prompt_result[
                        "selected_synonym"
                    ] = (
                        synonym
                    )

                    prompt_result[
                        "selected_synset"
                    ] = (
                        matching_synsets[
                            0
                        ].get(
                            "synset"
                        )
                        if matching_synsets
                        else None
                    )

                    prompt_result[
                        "selected_occurrence_number"
                    ] = (
                        occurrence_number
                    )

                    prompt_result[
                        "system_prompt_transformed"
                    ] = (
                        transformed_prompt
                    )

                    prompt_result[
                        "selection_status"
                    ] = (
                        "approved"
                    )

                    prompt_finished = True

                    break

            # -----------------------------------------------------
            # ADD COMPLETED CANDIDATE AUDIT
            # -----------------------------------------------------

            prompt_result[
                "candidate_reviews"
            ].append(
                candidate_review
            )

            # Save candidate-level completion.
            save_jsonl(
                OUTPUT_FILE,
                output_rows
                + [prompt_result]
            )

            # Stop reviewing later target words
            # once one valid substitution is approved.
            if prompt_finished:

                break

        # ---------------------------------------------------------
        # HANDLE UNRESOLVED PROMPT
        # ---------------------------------------------------------

        if not prompt_finished:

            prompt_result[
                "selection_status"
            ] = (
                "no_contextually_valid_"
                "substitution_selected"
            )

        # Commit completed prompt.
        output_rows.append(
            prompt_result
        )

        # Save after every completed prompt.
        save_jsonl(
            OUTPUT_FILE,
            output_rows
        )

        # ---------------------------------------------------------
        # DISPLAY PROMPT RESULT
        # ---------------------------------------------------------

        if prompt_finished:

            print(
                "\nAPPROVED SUBSTITUTION:"
            )

            print(
                f"{prompt_result['selected_word']} "
                f"-> "
                f"{prompt_result['selected_synonym']}"
            )

            print(
                f"Occurrence: "
                f"#{prompt_result['selected_occurrence_number']}"
            )

            print(
                "\nTRANSFORMED SYSTEM PROMPT:"
            )

            print(
                prompt_result[
                    "system_prompt_transformed"
                ]
            )

        else:

            print(
                "\nNo substitution was "
                "approved for this prompt."
            )

    # -----------------------------------------------------------------
    # FINAL SUMMARY
    # -----------------------------------------------------------------

    print(
        "\n"
        + "=" * 110
    )

    print(
        "CONTEXTUAL SYNONYM REVIEW COMPLETE"
    )

    print(
        "=" * 110
    )

    approved_count = sum(
        row.get(
            "selection_status"
        )
        == "approved"
        for row in output_rows
    )

    unresolved_count = (
        len(output_rows)
        - approved_count
    )

    print(
        f"\nPrompts with approved "
        f"substitution: "
        f"{approved_count}"
    )

    print(
        f"Prompts without approved "
        f"substitution: "
        f"{unresolved_count}"
    )

    print(
        f"\nResults saved to:\n"
        f"{OUTPUT_FILE}"
    )


if __name__ == "__main__":

    main()